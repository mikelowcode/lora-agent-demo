    # -----------------------------------------------------------------------
    # Priority 1c — Pinned-wiki-page diff short-circuit
    # -----------------------------------------------------------------------

    def _priority1c_pinned_diff(
        self,
        instruction: str,
        lowered:     str,
    ) -> RoutingPlan | None:
        """
        Priority 1c — pinned-wiki-page diff short-circuit. Fires only when
        exactly one wiki-pinned SessionFile is currently attached: the pin
        has already disambiguated the target, so target-name extraction and
        resolve_graph_target() are skipped entirely. Broader diff-keyword
        match than P1b (substring anywhere, not a leading phrase) since no
        remainder needs to be parsed out — see _DIFF_KEYWORDS.

        Also folds in any Priority 3 tool signal (_priority3_tool()) present
        in the same instruction, so "fetch this URL and update the pinned
        page to reflect it" dispatches the tool and carries diff_target
        alongside tools_to_call on one compound RoutingPlan.

        Returns None (falls through to normal priority evaluation,
        including P1b unchanged) when: zero or 2+ wiki pins are attached, or
        no _DIFF_KEYWORDS substring is present in the instruction.
        """
        pinned = [
            f for f in _session_files.get_files() if f.source == "wiki_pin"
        ]
        if len(pinned) != 1:
            return None

        if not any(kw in lowered for kw in _DIFF_KEYWORDS):
            return None

        stem = pinned[0].filename.removesuffix(".md")

        tool_plan = self._priority3_tool(lowered, instruction)
        tools_to_call      = tool_plan.tools_to_call      if tool_plan else []
        tool_signal_source = tool_plan.tool_signal_source if tool_plan else None
        file_op_deferred   = tool_plan.file_op_deferred   if tool_plan else False
        file_op_path       = tool_plan.file_op_path       if tool_plan else None
        file_op_action     = tool_plan.file_op_action     if tool_plan else None

        logger.debug(
            "Planner: Priority 1c matched — diff_target=%r (pinned; tools=%s).",
            stem, tools_to_call,
        )
        return RoutingPlan(
            agent              = "wiki_agent",
            fetch_episodic     = False,
            fetch_rag          = False,
            priority           = 1,
            diff_target        = stem,
            diff_target_source = "pinned",
            tools_to_call      = tools_to_call,
            compound           = bool(tools_to_call) or file_op_deferred,
            tool_signal_source = tool_signal_source,
            file_op_deferred   = file_op_deferred,
            file_op_path       = file_op_path,
            file_op_action     = file_op_action,
        )

    # -----------------------------------------------------------------------
    # Priority 1b — Diff-only wiki update
    # -----------------------------------------------------------------------

    def _priority1b_diff(
        self,
        instruction: str,
        lowered:     str,
    ) -> RoutingPlan | None:
        """
        Priority 1b — diff-only wiki update ("update page X to reflect Y",
        with no raw file involved). Only reached when Priority 1 (ingest)
        did not already match, so an ingest instruction that happens to
        also contain a diff keyword still takes the ingest path unchanged.

        Resolves the target page name via the same resolve_graph_target()
        three-tier pipeline Priority 3c uses, fed by
        memory_manager.list_graph_node_stems(). On successful resolution,
        routes to wiki_agent with diff_target set. On a keyword match with
        failed/ambiguous resolution (or no MemoryManager to resolve
        against), routes to conversational_agent with no tools/retrieval so
        the model can ask the user which page they mean — the turn is
        claimed either way; it deliberately does NOT fall through to P2+
        on an unresolved target. Both P1 and P1b are "write to storage"
        intents and stay on the same deterministic, early footing ahead of
        P2 memory commands (Michael's decision, 2026-07-09).

        Returns None only when no _DIFF_KEYWORDS lead phrase is present.
        """
        remainder = extract_diff_query(instruction)
        if remainder is None:
            return None

        if self._memory_manager is None:
            logger.debug(
                "Planner: Priority 1b matched keyword but no MemoryManager — "
                "routing to conversational_agent for clarification."
            )
            return RoutingPlan(
                agent          = "conversational_agent",
                fetch_episodic = False,
                fetch_rag      = False,
                priority       = 1,
            )

        try:
            candidate_stems = self._memory_manager.list_graph_node_stems()
        except Exception as exc:
            logger.warning(
                "Planner: Priority 1b — list_graph_node_stems failed: %s", exc
            )
            candidate_stems = []

        resolved_stem = resolve_graph_target(remainder, candidate_stems)

        if resolved_stem is None:
            logger.debug(
                "Planner: Priority 1b — target resolution failed for %r; "
                "routing to conversational_agent for clarification.",
                remainder,
            )
            return RoutingPlan(
                agent          = "conversational_agent",
                fetch_episodic = False,
                fetch_rag      = False,
                priority       = 1,
            )

        logger.debug(
            "Planner: Priority 1b matched — diff_target=%r.", resolved_stem
        )
        return RoutingPlan(
            agent          = "wiki_agent",
            fetch_episodic = False,
            fetch_rag      = False,
            priority       = 1,
            diff_target    = resolved_stem,
        )

